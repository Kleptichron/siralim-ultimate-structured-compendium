function migrateAction(a) {
  const params = { ...(a.params ?? {}) };
  const out = { ...a };
  const qualifiers = new Set(out.qualifiers ?? []);
  if (params.actor) { out.actor = params.actor; delete params.actor; }
  if (params.random) { qualifiers.add('random'); delete params.random; }
  if (params.stolen) { qualifiers.add('stolen'); delete params.stolen; }
  if (params.receivesStolen) { qualifiers.add('stolen'); delete params.receivesStolen; params.note = 'receives the stolen stats'; }
  if (params.permanent) { qualifiers.add('permanent'); delete params.permanent; }
  if (params.kind === 'buff' || params.kind === 'debuff') { out.statusKind = params.kind; delete params.kind; }
  if (params.dealt) { out.flow = 'dealt'; delete params.dealt; }
  if (params.taken) { out.flow = 'taken'; delete params.taken; }
  if (params.received) { out.flow = 'taken'; delete params.received; }
  if (out.magnitude?.perCount !== undefined) {
    out.magnitude = { ...out.magnitude, per: out.magnitude.perCount };
    delete out.magnitude.perCount;
  }
  if (out.magnitude?.scaleStatPct !== undefined) {
    out.magnitude = { ...out.magnitude, scalePct: out.magnitude.scaleStatPct };
    delete out.magnitude.scaleStatPct;
  }
  if (qualifiers.size) out.qualifiers = [...qualifiers];
  if (Object.keys(params).length) out.params = params; else delete out.params;
  return out;
}

let migrated = 0;
for (const dir of readdirSync('data/annotations')) {
  for (const f of readdirSync(`data/annotations/${dir}`)) {
    if (!f.endsWith('.json')) continue;
    const path = `data/annotations/${dir}/${f}`;
    const ann = JSON.parse(readFileSync(path, 'utf8'));
    if (ann.provenance === 'machine') continue; // regenerated by extract.js
    if (ann.schemaVersion !== 0) continue;
    ann.rules = (ann.rules ?? []).map(r => {
      const rule = { ...r, actions: (r.actions ?? []).map(migrateAction) };
      if (rule.modifiesDefault === false) delete rule.modifiesDefault;
      return rule;
    });
    for (const [ri, ai, patch] of PATCHES[ann.id] ?? []) {
      const a = ann.rules[ri].actions[ai];
      const { dropParams = [], magnitude, ...rest } = patch;
      Object.assign(a, rest);
      if (magnitude) a.magnitude = { ...(a.magnitude ?? {}), ...magnitude };
      if (a.params) {
        for (const k of dropParams) delete a.params[k];
        if (!Object.keys(a.params).length) delete a.params;
      }
    }
    ann.schemaVersion = 1;
    writeFileSync(path, JSON.stringify(ann, null, 2) + '\n');
    migrated++;
  }
}
console.log(`migrated ${migrated} annotations to schema v1`);
